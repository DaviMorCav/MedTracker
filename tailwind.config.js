const toVars = (palette) => {
  const vars = {};
  for (const [name, shades] of Object.entries(palette))
    for (const [shade, rgb] of Object.entries(shades)) vars[`--c-${name}-${shade}`] = rgb;
  return vars;
};

const colors = {};
for (const [name, shades] of Object.entries(light)) {
  colors[name] = {};
  for (const shade of Object.keys(shades))
    colors[name][shade] = `rgb(var(--c-${name}-${shade}) / <alpha-value>)`;
}

